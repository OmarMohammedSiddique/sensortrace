"""Synthetic demonstration data for onboarding. Everything created here is flagged ``is_demo``."""

from __future__ import annotations

from typing import Any

from sensortrace_engine.synthetic import SyntheticSensor, encode_jpeg
from sqlalchemy import select
from sqlalchemy.orm import Session

from .audit import audit
from .jobs import enqueue
from .models import (
    Device,
    Evidence,
    Fingerprint,
    Investigation,
    ReferenceImage,
    Sensor,
    User,
)
from .services import ingest_upload, purge_device, purge_investigation, store_image
from .storage import get_storage

SHAPE = (512, 640)
N_REFERENCE = 20
DEMO_NOTE = (
    "Synthetic demonstration data generated by SensorTrace. The simulated sensors follow a textbook noise "
    "model without real camera processing, so results here say nothing about real-world accuracy."
)


def has_demo(db: Session, user: User) -> bool:
    return db.scalar(select(Device.id).where(Device.user_id == user.id, Device.is_demo.is_(True)).limit(1)) is not None


def remove_demo(db: Session, user: User) -> None:
    for inv in db.scalars(select(Investigation).where(Investigation.user_id == user.id, Investigation.is_demo.is_(True))):
        purge_investigation(db, inv)
    for dev in db.scalars(select(Device).where(Device.user_id == user.id, Device.is_demo.is_(True))):
        purge_device(db, dev)
    audit(db, user.id, "demo.removed")
    db.commit()


def seed_demo(db: Session, user: User) -> dict[str, Any]:
    """Create two synthetic cameras with reference images, a demo investigation and three questioned images."""
    st = get_storage()
    seed = int(user.id.int % 1_000_000)
    sensors = {name: SyntheticSensor(seed + i, SHAPE, prnu_strength=0.012) for i, name in enumerate("ABC")}
    out: dict[str, Any] = {"sensor_ids": [], "evidence_ids": [], "job_ids": []}

    for name in "AB":
        dev = Device(user_id=user.id, name=f"Demo camera {name} (synthetic)", make="SensorTrace Synthetic", model="Model S",
                     device_type="dedicated_camera", pipeline_class="conventional", serial_number=f"DEMO-{name}", notes=DEMO_NOTE, is_demo=True)  # fmt: skip
        db.add(dev)
        db.flush()
        sensor = Sensor(
            user_id=user.id,
            device_id=dev.id,
            name="Main sensor",
            position="main",
            notes=DEMO_NOTE,
        )
        db.add(sensor)
        db.flush()
        for i in range(N_REFERENCE):
            data = encode_jpeg(sensors[name].capture(i, flat=True), 97)
            img, q = ingest_upload(data, "reference")
            key, pkey = store_image(st, user.id, data, img, "references")
            db.add(ReferenceImage(user_id=user.id, sensor_id=sensor.id, filename=f"demo-{name}-flat-{i + 1:02d}.jpg", sha256=img.sha256,
                                  size_bytes=img.size_bytes, mime_type=img.mime_type, width=img.width, height=img.height,
                                  image_metadata=img.metadata, quality=q.to_dict(), object_key=key, preview_key=pkey))  # fmt: skip
        fp = Fingerprint(user_id=user.id, sensor_id=sensor.id, version=1, status="pending")
        db.add(fp)
        db.flush()
        out["sensor_ids"].append(str(sensor.id))
        out["job_ids"].append(str(enqueue(db, user, "fingerprint", "fingerprint", fp.id).id))

    inv = Investigation(
        user_id=user.id,
        title="Demo investigation (synthetic)",
        reference="DEMO-001",
        description=DEMO_NOTE,
        is_demo=True,
    )
    db.add(inv)
    db.flush()
    for name, label in (
        ("A", "from demo camera A"),
        ("B", "from demo camera B"),
        ("C", "from a camera that is not enrolled"),
    ):
        data = encode_jpeg(sensors[name].capture(1000), 95)
        img, q = ingest_upload(data, "questioned")
        key, pkey = store_image(st, user.id, data, img, "evidence")
        ev = Evidence(user_id=user.id, investigation_id=inv.id, filename=f"demo-questioned-{name}.jpg", category="questioned", sha256=img.sha256,
                      size_bytes=img.size_bytes, mime_type=img.mime_type, width=img.width, height=img.height, dhash=img.dhash,
                      image_metadata=img.metadata, quality=q.to_dict(), object_key=key, preview_key=pkey, is_demo=True,
                      acquisition={"source": f"Synthetic image {label}", "method": "Generated by SensorTrace", "notes": DEMO_NOTE,
                                   "acquired_at": "", "acquired_by": ""},
                      provenance={**img.provenance, "synthetic": True, "exif_orientation": img.exif_orientation})  # fmt: skip
        db.add(ev)
        db.flush()
        out["evidence_ids"].append(str(ev.id))
    out["investigation_id"] = str(inv.id)
    audit(db, user.id, "demo.created", investigation_id=inv.id)
    db.commit()
    return out
