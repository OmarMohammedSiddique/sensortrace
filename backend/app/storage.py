"""Private object storage with three logical buckets.

``evidence``  original uploaded bytes, written once and never modified
``derived``   artefacts computed from evidence (previews, fingerprints, visualisations)
``results``   reports and exports

Object keys are generated by the server (``<user-id>/<uuid>``); user-supplied
filenames never reach the storage layer. Nothing is publicly readable: all
access goes through the API with authorisation or a signed, expiring token.
"""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Protocol

from .config import Settings, get_settings

BUCKETS = ("evidence", "derived", "results")


class Storage(Protocol):
    def put(
        self,
        bucket: str,
        key: str,
        data: bytes,
        content_type: str = "application/octet-stream",
    ) -> None: ...
    def get(self, bucket: str, key: str) -> bytes: ...
    def delete(self, bucket: str, key: str) -> None: ...
    def exists(self, bucket: str, key: str) -> bool: ...
    def delete_prefix(self, bucket: str, prefix: str) -> int: ...
    def ready(self) -> bool: ...


def _check(bucket: str, key: str) -> None:
    if bucket not in BUCKETS:
        raise ValueError(f"unknown bucket {bucket!r}")
    parts = key.split("/")
    if not key or key.startswith("/") or any(p in ("", ".", "..") for p in parts) or "\\" in key or "\x00" in key:
        raise ValueError("invalid object key")


class LocalStorage:
    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()
        for b in BUCKETS:
            (self.root / b).mkdir(parents=True, exist_ok=True)

    def _path(self, bucket: str, key: str) -> Path:
        _check(bucket, key)
        p = (self.root / bucket / key).resolve()
        if not p.is_relative_to(self.root / bucket):
            raise ValueError("invalid object key")
        return p

    def put(
        self,
        bucket: str,
        key: str,
        data: bytes,
        content_type: str = "application/octet-stream",
    ) -> None:
        p = self._path(bucket, key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_name(p.name + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(p)

    def get(self, bucket: str, key: str) -> bytes:
        try:
            return self._path(bucket, key).read_bytes()
        except FileNotFoundError:
            raise KeyError(key) from None

    def delete(self, bucket: str, key: str) -> None:
        self._path(bucket, key).unlink(missing_ok=True)

    def exists(self, bucket: str, key: str) -> bool:
        return self._path(bucket, key).is_file()

    def delete_prefix(self, bucket: str, prefix: str) -> int:
        d = self._path(bucket, prefix.rstrip("/"))
        if not d.is_dir():
            return 0
        n = sum(1 for p in d.rglob("*") if p.is_file())
        shutil.rmtree(d)
        return n

    def ready(self) -> bool:
        return self.root.is_dir()


class S3Storage:
    def __init__(self, s: Settings) -> None:
        import boto3
        from botocore.config import Config

        self._buckets = {
            "evidence": s.s3_bucket_evidence,
            "derived": s.s3_bucket_derived,
            "results": s.s3_bucket_results,
        }
        self._c = boto3.client(
            "s3",
            endpoint_url=s.s3_endpoint_url,
            region_name=s.s3_region,
            aws_access_key_id=s.s3_access_key,
            aws_secret_access_key=s.s3_secret_key,
            config=Config(
                signature_version="s3v4",
                retries={"max_attempts": 4, "mode": "standard"},
            ),
        )

    def ensure_buckets(self) -> None:
        from botocore.exceptions import ClientError

        for name in self._buckets.values():
            try:
                self._c.head_bucket(Bucket=name)
            except ClientError:
                self._c.create_bucket(Bucket=name)
            # Block every form of public access where the service supports it.
            try:
                self._c.put_public_access_block(
                    Bucket=name,
                    PublicAccessBlockConfiguration={
                        "BlockPublicAcls": True,
                        "IgnorePublicAcls": True,
                        "BlockPublicPolicy": True,
                        "RestrictPublicBuckets": True,
                    },  # fmt: skip
                )
            except Exception:
                pass

    def put(
        self,
        bucket: str,
        key: str,
        data: bytes,
        content_type: str = "application/octet-stream",
    ) -> None:
        _check(bucket, key)
        self._c.put_object(Bucket=self._buckets[bucket], Key=key, Body=data, ContentType=content_type)

    def get(self, bucket: str, key: str) -> bytes:
        from botocore.exceptions import ClientError

        _check(bucket, key)
        try:
            return self._c.get_object(Bucket=self._buckets[bucket], Key=key)["Body"].read()
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in ("NoSuchKey", "404"):
                raise KeyError(key) from None
            raise

    def delete(self, bucket: str, key: str) -> None:
        _check(bucket, key)
        self._c.delete_object(Bucket=self._buckets[bucket], Key=key)

    def exists(self, bucket: str, key: str) -> bool:
        from botocore.exceptions import ClientError

        _check(bucket, key)
        try:
            self._c.head_object(Bucket=self._buckets[bucket], Key=key)
            return True
        except ClientError:
            return False

    def delete_prefix(self, bucket: str, prefix: str) -> int:
        _check(bucket, prefix.rstrip("/"))
        n = 0
        pager = self._c.get_paginator("list_objects_v2")
        for page in pager.paginate(Bucket=self._buckets[bucket], Prefix=prefix.rstrip("/") + "/"):
            objs = [{"Key": o["Key"]} for o in page.get("Contents", [])]
            if objs:
                self._c.delete_objects(Bucket=self._buckets[bucket], Delete={"Objects": objs})
                n += len(objs)
        return n

    def ready(self) -> bool:
        try:
            self._c.head_bucket(Bucket=self._buckets["evidence"])
            return True
        except Exception:
            return False


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        s = get_settings()
        if s.storage_backend == "s3":
            st = S3Storage(s)
            st.ensure_buckets()
            _storage = st
        else:
            _storage = LocalStorage(s.storage_local_path)
    return _storage


def reset_storage() -> None:
    global _storage
    _storage = None
