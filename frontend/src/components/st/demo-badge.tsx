import { FlaskConical } from "lucide-react";

import { cn } from "@/lib/utils";

/**
 * Marks synthetic demonstration data. Render it next to the name of ANY object whose
 * `is_demo` is true (release-blocking rule). Pass `when={item.is_demo}` to avoid a ternary.
 */
export function DemoBadge({ when = true, className }: { when?: boolean | null; className?: string }) {
  if (!when) return null;
  return (
    <span
      title="Generated by SensorTrace for demonstration. Not from a real camera."
      className={cn(
        "inline-flex h-5 w-fit shrink-0 items-center gap-1 rounded-md border border-dashed border-brand-border bg-brand-subtle px-1.5 align-middle text-[0.6875rem] font-medium whitespace-nowrap text-brand",
        className,
      )}
    >
      <FlaskConical aria-hidden="true" className="size-3" />
      Synthetic demo
    </span>
  );
}
